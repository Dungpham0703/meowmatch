const {chromium} = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.DEMO_URL || 'http://127.0.0.1:8000';
(async () => {
  fs.mkdirSync('artifacts', {recursive:true});
  const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const health = await (await page.request.get(`${base}/api/health`)).json();
  const catalogSize = Object.keys(JSON.parse(fs.readFileSync('stickers_cache.json','utf8'))).length;
  assert.equal(health.sticker_count,catalogSize);
  assert.equal(health.total_vectors,catalogSize);
  assert.equal(health.model,'gemini-embedding-2');
  assert.equal(health.ready,true);
  fs.writeFileSync('artifacts/health.json',JSON.stringify(health,null,2));
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/search/compare'));
  await page.goto(base);
  const response = await responsePromise;
  assert.equal(response.status(),200);
  const result = await response.json();
  assert.equal(await page.locator('html').getAttribute('lang'),'en');
  assert.match(await page.title(),/MeowMatch/);
  assert.equal(await page.locator('#heading-keyword').textContent(),'Keyword Search');
  assert.equal(await page.locator('#panel-text').count(),0);
  assert.deepEqual(Object.keys(result.methods).sort(),['image','keyword']);
  assert.equal(await page.locator('#heading-image').textContent(),'Image Semantic Search');
  assert.equal(await page.locator('.column-heading > p').count(),0);
  assert.ok(result.methods.image.results.every(item => !/[ĂăÂâĐđÊêÔôƠơƯư\u1ea0-\u1ef9]/.test([item.name,item.caption,...item.tags].join(' '))));
  const ten = await (await page.request.post(`${base}/api/search/compare`,{data:{query:result.query,top_k:10}})).json();
  assert.equal(ten.methods.image.results.length,10);
  assert.equal((await page.request.post(`${base}/api/search/compare`,{data:{query:'   '}})).status(),422);
  assert.equal((await page.request.get(`${base}/api/vectors/missing`)).status(),404);
  await page.locator('#results[aria-busy=false]').waitFor();
  for (const kind of ['keyword','image']) {
    assert.equal(result.methods[kind].status,'ok');
    assert.ok(result.methods[kind].results.length > 0);
    assert.equal(await page.locator(`#list-${kind} .meme-card`).count(), result.methods[kind].results.length);
  }
  await page.locator('#list-image .meme-card').first().click();
  assert.equal(await page.locator('#detail-dialog').evaluate(el=>el.open), true);
  assert.equal(await page.locator('#detail-ranks .rank-row').count(),2);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#detail-dialog').evaluate(el=>el.open),false);
  await page.locator('#page-title').click();
  await page.waitForTimeout(200);
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.locator('#query').fill('judgmental cat staring at me');
  const next = page.waitForResponse(r=>r.url().endsWith('/api/search/compare'));
  await page.locator('#search-button').click();
  const nextResult = await (await next).json();
  await page.locator('#results[aria-busy=false]').waitFor();
  assert.equal(nextResult.query,'judgmental cat staring at me');
  for(const group of Object.values(nextResult.methods)) assert.equal(group.status,'ok');
  fs.writeFileSync('artifacts/live-results.json',JSON.stringify(nextResult,null,2));
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.locator('#panel-keyword').isVisible(),true);
  await page.locator('#tab-image').click();
  assert.equal(await page.locator('#panel-image').isVisible(),true);
  assert.equal(await page.locator('#panel-keyword').isVisible(),false);
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#tab-keyword').getAttribute('aria-selected'),'true');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  await page.waitForTimeout(200);
  await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
  await page.setViewportSize({width:768,height:1024});
  assert.equal(await page.locator('#panel-keyword').isVisible(),true);
  assert.equal(await page.locator('#panel-image').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  // A failing provider leaves the keyword list usable.
  await page.route('**/api/search/compare', route => {
    const body = route.request().postDataJSON();
    const data = structuredClone(result); data.query = body.query;
    for(const kind of ['image']) data.methods[kind] = {...data.methods[kind],status:'error',results:[],error:'Gemini is rate-limited. Please try again shortly.'};
    return route.fulfill({json:data});
  });
  await page.locator('#query').fill('quota test');
  await page.locator('#search-button').click();
  await page.locator('#list-image .retry-button').waitFor();
  assert.ok(await page.locator('#list-keyword .meme-card').count()>0);
  await page.unroute('**/api/search/compare');
  // The earlier request may finish later; it must never replace the newer one.
  await page.route('**/api/search/compare', async route => {
    const query = route.request().postDataJSON().query;
    await new Promise(r=>setTimeout(r,query === 'old query' ? 350 : 10));
    try { await route.fulfill({json:{...result,query}}); } catch {}
  });
  await page.locator('#query').fill('old query');
  await page.locator('#search-button').click();
  await page.waitForTimeout(30);
  await page.locator('#query').fill('new query');
  await page.locator('#search-button').click();
  await page.waitForTimeout(500);
  assert.match(await page.locator('#query-summary').textContent(),/new query/);
  await page.unroute('**/api/search/compare');
  await page.route('**/api/search/compare',route=>route.fulfill({status:503,json:{detail:'Database unavailable'}}));
  await page.locator('#search-button').click();
  await page.locator('#form-error:not([hidden])').waitFor();
  assert.equal(await page.locator('.retry-button').count(),2);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: live 2-way search, modal, desktop/mobile/tablet, keyboard tabs, provider failure, stale responses, HTTP failure.');
})().catch(error=>{console.error(error);process.exit(1)});
